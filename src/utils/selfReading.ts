const isMbti = (t?: string): t is string => !!t && /^[EI][NS][TF][JP]$/i.test(t);

/**
 * 本人の「あなたってこんな人」。
 * @param pillar 日柱（例: '甲子'。FortuneResult.myPillar）
 * @param star 本命星（例: '一白水星 (水)'。FortuneResult.myStar）
 * @param mbti 16タイプ（例: 'INFP'。未選択は 'UNKNOWN' や空文字）
 */
export function getSelfReading(pillar: string, star: string, mbti?: string): SelfReading | null {
  const stem = pillar?.[0];
  const branch = pillar?.[1];
  const core = stem ? CORE[stem] : undefined;
  const love = stem && branch ? LOVE[getJuniUn(stem, branch)] : undefined;
  if (!core || !love) return null;
  const starName = (star || '').split(' ')[0];
  const code = isMbti(mbti) ? mbti.toUpperCase() : '';
  const habit = code ? HABIT_MBTI[code] : HABIT_STAR[starName];
  const items: SelfReadingItem[] = [
    { label: 'ふだんのあなた', text: core },
    { label: '恋をするとあなたは', text: love }
  ];
  if (habit) items.push({ label: 'ついやってしまうこと', text: habit });
  return { items, key: `${pillar}-${code || starName}` };
}
