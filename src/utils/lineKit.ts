export function buildLineKit(oppMbtiCode: string | undefined, oppPillar: string | undefined): LineKit | null {
  const stem = (oppPillar || '').charAt(0);
  const element = STEM_ELEMENT[stem];
  const known = isMbti(oppMbtiCode);
  if (!known && !element) return null;

  const set = known ? MBTI_SCENES[oppMbtiCode!.toUpperCase()] : ELEMENT_SCENES[element];
  const scenes: LineKitScene[] = SCENE_ORDER.map(key => ({
    key,
    label: SCENE_LABELS[key],
    message: set[key][0],
    why: set[key][1]
  }));

  const style: LineKit['style'] = known ? styleFromMbti(oppMbtiCode!) : [];
  if (element) {
    style.push({ label: '生まれ持った星から見た、響く言葉', text: STEM_POINT[stem] });
    if (!known) style.unshift({ label: 'LINEの好み', text: ELEMENT_STYLE[element] });
  }

  return {
    basis: known
      ? `${oppMbtiCode!.toUpperCase()}タイプ${element ? ' × 生まれ持った星' : ''}から分析`
      : '生まれ持った星から分析',
    style,
    scenes,
    fixes: known ? fixesFromMbti(oppMbtiCode!) : GENERIC_FIXES,
    note: known ? undefined : 'お相手の性格タイプ（MBTI）を入れると、返信のペースや誘い方まで、もっと細かく分析できます。'
  };
}
