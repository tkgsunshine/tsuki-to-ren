/** columnsData.ts から公開済みのコラムを読む（prerender-columns.js と同じ読み方） */
export function loadColumns() {
  const file = path.resolve(__dirname, '../src/data/columnsData.ts');
  const m = fs.readFileSync(file, 'utf-8').match(/export const COLUMNS_DATA: ColumnArticle\[\] = (\[[\s\S]*?\]);/);
  if (!m) return [];
  try {
    return JSON.parse(m[1]);
  } catch {
    return [];
  }
}
