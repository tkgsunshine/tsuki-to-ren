// 日付などから決まる値（同じ日・同じ型なら、いつ実行しても同じ事実になる）
const hashOf = (s) => {
  let h = 0;
  for (const ch of s) h = (h * 31 + ch.codePointAt(0)) >>> 0;
  return h;
};
const pickN = (arr, n, seed) => {
  const pool = [...arr];
  const out = [];
  let h = hashOf(seed);
  while (out.length < n && pool.length) {
    out.push(pool.splice(h % pool.length, 1)[0]);
    h = Math.floor(h / 7) + 13;
  }
  return out;
};

