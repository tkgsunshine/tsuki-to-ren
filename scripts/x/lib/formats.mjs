const MEDAL = { 1: '🥇', 2: '🥈', 3: '🥉' };
/** 順位の1件（メダル＋順位＋守護獣＋点数、次の行に一言）。1件ずつ空行を入れると見やすい。medal=false は、ワースト用（メダルなし） */
const rankBlock = (t, i, medal = true) => `${medal ? MEDAL[t.rank] || '' : ''}${t.rank}位 ${t.name} ${t.score}点\n${pairNote(t.score, i)}`;
export function buildBeastPairRanking(date) {
  const beasts = beastList();
  const anchor = beasts[Math.floor(dayPillar(date).days / 2) % 60]; // 2日に1回出る型。60回で全タイプが主役
  const others = beasts
    .filter((b) => b.index !== anchor.index)
    .map((b) => ({ name: b.name, score: getPillarPairScore(anchor.stem, anchor.branch, b.stem, b.branch) }));
  const desc = [...others].sort((x, y) => y.score - x.score || x.name.localeCompare(y.name, 'ja'));
  const ranked = withRanks(desc);
  const fits = (text) => weightedLength(text) <= 400; // Xプレミアム（2026-10-31）: プロフィールへの一言・リンクが入るので、280から400に
  // 本文: 4位から（点数だけの1行ずつ。280に収まる件数。最大8）。1〜3位は、リプ欄に出す（2026-10-23〜。先を見たくなるように）
  const top = ranked.filter((t) => t.rank <= 3).slice(0, 5); // 3位が同点のときは、同点の全員を、1〜3位として、リプ欄に出す
  let k = 8;
  const mk0 = (n) => ({ mid: ranked.slice(top.length, top.length + n), get text() { return [`❤️ ${anchor.full}の相性ランキング（100点満点）`, '', `【${this.mid[0].rank}位〜${this.mid.at(-1).rank}位】`, this.mid.map((t) => `${t.rank}位 ${t.name} ${t.score}点`).join('\n'), '', 'いちばん相性がいい1〜3位は、リプ欄に🌙', 'あなたの守護獣は何位？', '', BEAST_CTA, '-月-'].join('\n'); } });
  let r0 = mk0(k);
  while (!fits(r0.text) && k > 2) r0 = mk0(--k);
  const text = r0.text;
  // 返信1: 1〜3位（メダル＋一言）
  // 一言つきは先頭3件まで。同点で4件目以降になるぶんは、点数だけの1行（280字に収めるため）
  const mkReply = (n) => ['【相性ベスト3】', '', top.slice(0, n).map((t, i) => (i < 3 ? rankBlock(t, i) : `${MEDAL[t.rank] || ''}${t.rank}位 ${t.name} ${t.score}点`)).join('\n\n'), '', 'ぶつかりやすい守護獣は、さらにリプ欄に🌙', '-月-'].join('\n');
  let nTop = top.length;
  while (!fits(mkReply(nTop)) && nTop > 3) nTop--;
  const replyText = mkReply(nTop);
  // 返信2: ワースト（低い順）。280に収まる件数（最大5）。アプリの予告の行を、署名の直前に入れる
  const worstAll = withRanks([...desc].reverse());
  let w = 5;
  const mk2 = (n) => {
    const worst = worstAll.slice(0, n);
    return { worst, text: [`【${anchor.name}と、ぶつかりやすい守護獣 ワースト${n}】`, '（点数が低い順）', '', worst.map((t, i) => rankBlock(t, i, false)).join('\n\n'), '', BEAST_LINK, '-月-'].join('\n') };
  };
  let r2 = mk2(w);
  while (!fits(r2.text) && w > 2) r2 = mk2(--w);
  return { text, replyText, replyText2: r2.text, anchor: anchor.name, top, mid: r0.mid, worst: r2.worst };
}

// 月の満ち欠け（計算。2000-01-06 18:14 UTC の新月を基準に、朔望月 29.530589 日で数える）。投稿の「月のことば」の事実に使う
const SYNODIC = 29.530588853;
const NEW_MOON_REF = Date.UTC(2000, 0, 6, 18, 14);
export function moonPhase(date) {
  const noon = Date.parse(`${date}T03:00:00Z`); // JST正午
  const age = (((noon - NEW_MOON_REF) / 86400000) % SYNODIC + SYNODIC) % SYNODIC;
  const name = age < 1.5 || age > SYNODIC - 1.5 ? '新月（月が見えない夜。始まりの日）'
    : age < 6.5 ? '三日月ごろ（満ちはじめ）'
    : age < 8.5 ? '上弦の月（半分。決める・動くタイミングに例えられる）'
    : age < 13.2 ? '満ちていく月（十三夜ごろ）'
    : age < 14 ? 'ほぼ満月（満月の前夜ごろ。「満月」と言い切らず、「もうすぐ満月」と書く）'
    : age < 15.5 ? '満月（いちばん満ちた夜。気持ちがあふれやすいと言われる）'
    : age < 16.5 ? '満月を過ぎたばかりの月（十六夜ごろ。「満月の翌日」と書く）'
    : age < 21 ? '欠けはじめの月（手放し・ゆるめるころ）'
    : age < 23.5 ? '下弦の月（半分。ふり返り・整理に例えられる）'
    : '細くなる月（そっと終わらせ、休むころ）';
  return { age: Math.round(age * 10) / 10, name };
}

