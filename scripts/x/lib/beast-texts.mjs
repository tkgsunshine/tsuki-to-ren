/** 点数の帯（アプリの採点の区切りと同じ: 85 / 73 / 60 / 45） */
export function bandOf(score) {
  return score >= 85 ? 'A' : score >= 73 ? 'B' : score >= 60 ? 'C' : score >= 45 ? 'D' : 'E';
}

