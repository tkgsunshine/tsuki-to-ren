/** 候補の中から、キー（日付＋守護獣＋用途）で1つ選ぶ。同じ日・同じ守護獣なら、いつ実行しても同じ */
export function pickVariant(list, key) {
  let h = 0;
  for (const ch of key) h = (h * 31 + ch.codePointAt(0)) >>> 0;
  return list[h % list.length];
}

