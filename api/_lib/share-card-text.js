/** 鑑定結果の文から番号を探す。見つからなければ -1 */
export function shareTitleCode(title) {
  const head = /^【([^】]+)】/.exec(String(title || ''))?.[1];
  return SHARE_TITLES.findIndex(([h]) => h === head);
}
export function shareLineCode(oneLiner) {
  const s = String(oneLiner || '');
  return SHARE_LINES.findIndex((line) => s.endsWith(line));
}
